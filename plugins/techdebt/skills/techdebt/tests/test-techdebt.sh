  "  *--print-config*) cat <<'EOF'\n%s\nEOF\n  ;;\n  *) cat <<'EOF'\n%s\nEOF\n  exit 1 ;;\nesac\n"
  % (t, json.dumps(eslint_config), json.dumps(eslint_out)))
os.chmod(os.path.join(r, "node_modules/.bin/knip"), 0o755)
for exe in (".venv/bin/ruff", ".venv/bin/semgrep", "node_modules/.bin/eslint"):
    os.chmod(os.path.join(r, exe), 0o755)
PY

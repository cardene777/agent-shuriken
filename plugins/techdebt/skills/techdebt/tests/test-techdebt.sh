#!/usr/bin/env bash
# Tests for techdebt.py against throwaway repositories with dated commits.
# The fake knip and ruff in the fixture print fixed JSON, so nothing is downloaded or installed.
set -u

HERE="$(cd "$(dirname "$0")" && pwd)"
SCRIPT="$HERE/../scripts/techdebt.py"
PASS=0
FAIL=0
T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT
export TECHDEBT_HOME="$T/state"
R="$T/repo"
mkdir -p "$R"

ok() { PASS=$((PASS + 1)); printf 'ok    %s\n' "$1"; }
ng() { FAIL=$((FAIL + 1)); printf 'FAIL  %s\n' "$1"; }
check() { if eval "$2"; then ok "$1"; else ng "$1"; fi; }

g() { git -C "$R" -c user.name=test -c user.email=test@example.com "$@"; }
commit_at() { # <days ago> <message>
  local when
  when="$(python3 -c 'import datetime,sys; print((datetime.datetime.now()-datetime.timedelta(days=int(sys.argv[1]))).strftime("%Y-%m-%dT%H:%M:%S"))' "$1")"
  g add -A
  GIT_AUTHOR_DATE="$when" GIT_COMMITTER_DATE="$when" g commit -qm "$2"
}

g init -q
python3 - "$R" <<'PY'
import os, sys
r = sys.argv[1]
def w(p, text):
    p = os.path.join(r, p)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w").write(text)

body = "\n".join("    total += value * %d  # step %d" % (i, i) for i in range(64))
w("src/core.py", "# TODO: replace this loop with the batch API\n\n"
  "def big(values):\n    total = 0\n    for value in values:\n        if value > 0 and value < 100:\n            total += value\n"
  + body + "\n    return total\n\n\ndef small():\n    return 1\n")
w("src/util.py", "\n".join("def f%d(x):\n    return x + %d\n" % (i, i) for i in range(12)))
w("tests/test_util.py", "from src.util import f1\n\n\ndef test_f1():\n    assert f1(1) == 2\n")
w("src/lonely.py", 'LABEL = "# TODO in a string, not a comment"\n'
  + "\n".join("def g%d(x):\n    return x * %d\n" % (i, i) for i in range(12)))
w("src/thing-one.py", "\n".join("def h%d(x):\n    return x - %d\n" % (i, i) for i in range(12)))
w("tests/test-thing-one.sh", "python3 -c 'import sys'\n")
w("src/legacy.java", "class Legacy {\n  @Deprecated\n  void old() {}\n  String s = \"#[deprecated] in a string\";\n}\n")
shared = "\n".join("  const value%d = compute(input, %d) + offset * factor;" % (i, i) for i in range(12))
w("src/a.ts", "/** @deprecated use b instead */\nexport function a(input: number, offset: number, factor: number) {\n" + shared
  + "\n  return value0;\n}\n\n// TODO remove </script> once the page is gone\nfunction longOne(a: number) {\n  let x = 0;\n"
  + "\n".join("  if (a > %d) { x += %d; }" % (i, i) for i in range(66)) + "\n  return x;\n}\n")
w("src/b.ts", "export function b(input: number, offset: number, factor: number) {\n" + shared + "\n  return value1;\n}\n")
w("src/str.ts", 'export const s = "TODO later";\n// HACK: works around the old parser\nexport const t = 1;\n')
w("src/main.go", "package main\n\nfunc Process(items []int) int {\n\ttotal := 0\n"
  + "\n".join("\tif len(items) > %d {\n\t\ttotal += items[%d]\n\t}" % (i, i) for i in range(21)) + "\n\treturn total\n}\n")
w("src/big.js", "\n".join("export const c%d = %d;" % (i, i) for i in range(520)) + "\n")
w("vendor/lib.js", "// TODO vendored code is not ours\nexport const v = 1;\n")
w("src/gen.py", "# @generated by a tool\n# TODO generated marker\nx = 1\n")
w("package.json", '{"name": "fixture"}\n')
w(".gitignore", "node_modules/\n.venv/\n")
w("node_modules/.bin/knip", "#!/bin/sh\necho '{\"files\":[\"src/big.js\"],\"issues\":[{\"file\":\"src/a.ts\",\"exports\":[{\"name\":\"a\",\"line\":2}]}]}'\nexit 1\n")
w(".venv/bin/ruff", "#!/bin/sh\necho '[{\"code\":\"C901\",\"message\":\"big is too complex\",\"filename\":\"%s/src/core.py\",\"location\":{\"row\":3}}]'\n" % r)
os.chmod(os.path.join(r, "node_modules/.bin/knip"), 0o755)
os.chmod(os.path.join(r, ".venv/bin/ruff"), 0o755)
PY
commit_at 400 "first"
for d in 50 35 20 10; do
  printf '# change %s\n' "$d" >> "$R/src/core.py"
  commit_at "$d" "change $d"
done
printf '# FIXME: not committed yet\n' >> "$R/src/core.py"

run() { python3 "$SCRIPT" "$@"; }
run scan "$R" > "$T/scan.txt" 2> "$T/scan.err"
check "scan exits 0" "[ $? -eq 0 ]"
STATE="$(ls -d "$TECHDEBT_HOME"/repo-*)"
J="$STATE/scan.json"
q() { python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); print(eval(sys.argv[2]))' "$J" "$1"; }

check "the top ranked file is the busy long file" "[ \"\$(q 'd[\"ranked\"][0][\"file\"]')\" = src/core.py ]"
check "changes in the last 12 months are counted" "[ \"\$(q '[h[\"changes\"] for h in d[\"hotspots\"] if h[\"file\"]==\"src/core.py\"][0]')\" = 4 ]"
check "an old TODO is aged from git blame" "[ \"\$(q '[m[\"age_days\"] for m in d[\"markers\"] if m[\"kind\"]==\"TODO\" and m[\"file\"]==\"src/core.py\"][0] >= 399')\" = True ]"
check "an uncommitted FIXME has no age" "[ \"\$(q '[m[\"age_days\"] for m in d[\"markers\"] if m[\"kind\"]==\"FIXME\"][0]')\" = None ]"
check "HACK and deprecation markers are found" "[ \"\$(q 'sorted({m[\"kind\"] for m in d[\"markers\"]})')\" = \"['FIXME', 'HACK', 'TODO', 'deprecated']\" ]"
check "TODO inside a string is not a marker" "[ \"\$(q 'any(m[\"file\"] in (\"src/str.ts\",\"src/lonely.py\") and m[\"kind\"]==\"TODO\" for m in d[\"markers\"])')\" = False ]"
check "a deprecation annotation counts and one in a string does not" "[ \"\$(q '[m[\"line\"] for m in d[\"markers\"] if m[\"file\"]==\"src/legacy.java\"]')\" = '[2]' ]"
check "a test file named with hyphens matches its source" "[ \"\$(q 'any(u[\"file\"]==\"src/thing-one.py\" for u in d[\"untested\"])')\" = False ]"
check "vendored and generated files are skipped" "[ \"\$(q 'any(m[\"file\"] in (\"vendor/lib.js\",\"src/gen.py\") for m in d[\"markers\"])')\" = False ] && [ \"\$(q 'd[\"skipped_generated\"]')\" = 1 ]"
check "a file without a test is listed" "[ \"\$(q 'any(u[\"file\"]==\"src/lonely.py\" for u in d[\"untested\"])')\" = True ]"
check "a file with a matching test is not listed" "[ \"\$(q 'any(u[\"file\"]==\"src/util.py\" for u in d[\"untested\"])')\" = False ]"
check "a long Python function is measured exactly" "[ \"\$(q '[(f[\"lines\"],f[\"exact\"]) for f in d[\"functions\"] if f[\"name\"]==\"big\"][0]')\" = '(70, True)' ]"
check "a long TypeScript function is measured by braces" "[ \"\$(q '[(f[\"lines\"],f[\"exact\"]) for f in d[\"functions\"] if f[\"name\"]==\"longOne\"][0]')\" = '(70, False)' ]"
check "a long Go function is measured by braces" "[ \"\$(q '[f[\"lines\"] for f in d[\"functions\"] if f[\"name\"]==\"Process\"][0]')\" = 67 ]"
check "a short function is not listed" "[ \"\$(q 'any(f[\"name\"] in (\"small\",\"a\",\"b\") for f in d[\"functions\"])')\" = False ]"
check "a large file is listed" "[ \"\$(q '[f[\"lines\"] for f in d[\"large_files\"]]')\" = '[520]' ]"
check "a duplicated block is found with its length" "[ \"\$(q '[(x[\"a\"],x[\"b\"],x[\"lines\"]) for x in d[\"duplication\"]]')\" = \"[('src/a.ts', 'src/b.ts', 12)]\" ]"
check "installed knip ran" "[ \"\$(q '[(t[\"ran\"],len(t[\"findings\"])) for t in d[\"tools\"] if t[\"tool\"]==\"knip\"][0]')\" = '(True, 2)' ]"
check "installed ruff ran with paths relative to the root" "[ \"\$(q '[t[\"findings\"][0][\"file\"] for t in d[\"tools\"] if t[\"tool\"]==\"ruff\"][0]')\" = src/core.py ]"
check "the summary names the top file" "grep -q ' 1  src/core.py' \"$T/scan.txt\""
check "the scan wrote nothing to standard error" "[ ! -s \"$T/scan.err\" ]"
check "the state folder is private" "[ \"\$(stat -f %Lp \"$STATE\" 2>/dev/null || stat -c %a \"$STATE\")\" = 700 ]"

H="$STATE/report.html"
check "the report is written" "[ -s \"$H\" ]"
check "the report loads nothing from the network" "! grep -qiE '(src|href)=\"https?:|url\\(https?:|fetch\\(|XMLHttpRequest|<link ' \"$H\""
check "a marker containing a closing script tag does not break the page" "[ \"\$(grep -o '</script>' \"$H\" | wc -l | tr -d ' ')\" = 1 ]"
check "the report has English and Japanese labels" "grep -q 'Start here' \"$H\" && grep -q '最初に直す物' \"$H\""

# explain
printf '{"src/nowhere.py": {"what": "x", "why": "y", "action": "z"}}' > "$T/bad.json"
run explain --notes "$T/bad.json" "$R" > /dev/null 2> "$T/bad.err"
check "a note for a file that is not ranked is refused with exit 2" "[ $? -eq 2 ] && [ ! -f \"$STATE/notes.json\" ]"
printf '{"src/core.py": {"what": "The pricing loop", "why": "Every release touches it", "action": "Split big() by step"}}' > "$T/good.json"
run explain --notes "$T/good.json" "$R" > /dev/null 2>&1
check "notes are saved and shown in the report" "[ $? -eq 0 ] && grep -q 'Split big() by step' \"$H\""
run scan "$R" > /dev/null 2>&1
check "notes for files still ranked survive a new scan" "grep -q 'Every release touches it' \"$STATE/notes.json\""

# A folder inside the repository, a shorter window, and a folder outside git.
run scan "$R/src" > /dev/null 2>&1
SUB="$(ls -d "$TECHDEBT_HOME"/src-*)/scan.json"
check "a subfolder scan counts changes with paths relative to it" "[ \"\$(J=$SUB q '[h[\"changes\"] for h in d[\"hotspots\"] if h[\"file\"]==\"core.py\"][0]')\" = 4 ]"
run scan --months 1 "$R" > /dev/null 2>&1
check "--months narrows the window" "[ \"\$(q '[h[\"changes\"] for h in d[\"hotspots\"] if h[\"file\"]==\"src/core.py\"][0]')\" = 2 ]"
P="$T/plain"
mkdir -p "$P"
cp "$R/src/lonely.py" "$R/src/core.py" "$P/"
run scan "$P" > "$T/plain.txt" 2>&1
PJ="$(ls -d "$TECHDEBT_HOME"/plain-*)/scan.json"
check "a folder outside git is scanned without history" "[ \"\$(J=$PJ q '(d[\"git\"], d[\"files\"], len(d[\"hotspots\"]))')\" = '(False, 2, 0)' ]"
run scan "$T/missing" > /dev/null 2>&1
check "a missing folder exits 3" "[ $? -eq 3 ]"

printf '\n%d passed, %d failed\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]

    {"ruleId": "@typescript-eslint/no-deprecated", "line": 5, "message": "`substr` is deprecated.", "severity": 2},
    {"ruleId": "no-console", "line": 6, "message": "Unexpected console statement.", "severity": 1},
    {"ruleId": None, "line": 1, "message": "Parsing error: Unexpected token", "severity": 2, "fatal": True}]}]

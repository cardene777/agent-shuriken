def state_dir(root):
    base = os.environ.get("TECHDEBT_HOME") or os.path.join(os.path.expanduser("~"), ".local", "share", "techdebt")
    tag = hashlib.sha1(root.encode()).hexdigest()[:8]
    d = os.path.join(base, "%s-%s" % (os.path.basename(root) or "root", tag))
    os.makedirs(d, mode=0o700, exist_ok=True)
    os.chmod(base, 0o700)
    os.chmod(d, 0o700)
    return d


def git(root, *args, check=False):
    r = subprocess.run(["git", "-C", root] + list(args), capture_output=True)
    if check and r.returncode != 0:
        return None
    return r


def is_git(root):
    r = git(root, "rev-parse", "--show-toplevel")
    return r.returncode == 0


def repo_paths(root, in_git):
    """Every file of the repository outside the skipped folders, as paths relative to root."""
    if in_git:
        r = git(root, "ls-files", "-z", "--cached", "--others", "--exclude-standard")
        paths = [p for p in r.stdout.decode("utf-8", "replace").split("\0") if p]
    else:
        paths = []
        for d, dirs, files in os.walk(root):
            dirs[:] = [x for x in dirs if x not in SKIP_DIRS and not x.startswith(".")]
            for f in files:
                paths.append(os.path.relpath(os.path.join(d, f), root))
    return [p for p in sorted(set(paths)) if not any(x in SKIP_DIRS for x in p.split("/")[:-1])]


def list_files(root, in_git, paths=None):
    out = []
    for p in repo_paths(root, in_git) if paths is None else paths:
        parts = p.split("/")
        if parts[-1] in SKIP_FILES:
            continue
        name = parts[-1]
        if name.endswith((".min.js", ".min.css", ".map", ".snap", ".pb.go", "_pb2.py")):
            continue
        ext = os.path.splitext(name)[1].lower()
        if ext not in LANG:
            continue
        full = os.path.join(root, p)
        try:
            if not os.path.isfile(full) or os.path.islink(full) or os.path.getsize(full) > MAX_FILE_BYTES:
                continue
        except OSError:
            continue
        out.append(p)
    return out


def read_lines(root, path):
    with open(os.path.join(root, path), "rb") as fh:
        data = fh.read()
    if b"\0" in data[:4096]:
        return None
    return data.decode("utf-8", "replace").splitlines()


def is_test(path):
    parts = path.split("/")
    name = parts[-1]
    low = name.lower()
    if any(p.lower() in TEST_DIRS for p in parts[:-1]):
        return True
    return bool(
        low.startswith("test_") or re.search(r"(_test|\.test|\.spec|_spec|\.t)\.[a-z]+$", low)
        or re.search(r"(Test|Tests|Spec)\.(java|kt|swift|cs|scala|php)$", name)
    )


def stem(path):
    """The name a source file and its test file share: `foo` for foo.py, test_foo.py, foo.test.ts,
    FooTest.java, and test-foo.sh. Hyphens and underscores count as the same character."""
    name = os.path.basename(path)
    s = name.split(".")[0]
    s = re.sub(r"^(test[_-]|Test)", "", s)
    s = re.sub(r"([_-]test|[_-]spec|Tests|Test|Spec)$", "", s)
    return s.lower().replace("-", "_")



def describe(reason):
    k, v = reason["key"], reason["value"]
    return {
        "changes": "changed once" if v == 1 else "changed %d times" % v,
        "lines": "%d lines" % v,
        "long_functions": "%d long function%s" % (v, "" if v == 1 else "s"),
        "markers": "marker weight %d" % v,
        "dup_lines": "%d duplicated lines" % v,
        "untested": "no test file",
    }[k]


def tilde(path):
    """The path with the home folder written as `~`, so pasted output does not show the user name."""
    home = os.path.expanduser("~")
    return "~" + path[len(home):] if path == home or path.startswith(home + os.sep) else path


def print_summary(data, sdir):
    kinds = {}
    for m in data["markers"]:
        kinds[m["kind"]] = kinds.get(m["kind"], 0) + 1
    ages = [m["age_days"] for m in data["markers"] if m["age_days"] is not None]
    where = "HEAD %s on %s, " % (data["head"], data["branch"]) if data["git"] else "not a git repository, "
    print("techdebt scan of %s (%s%d source files, %d test files, %d commits in the last %d months)"
          % (tilde(data["root"]), where, data["files"], data["test_files"], data["commits"], data["months"]))
    print("Hotspots:       %d files changed 2 or more times" % len(data["hotspots"]))
    print("Markers:        %d%s%s" % (len(data["markers"]),
                                     " (" + ", ".join("%s %d" % kv for kv in sorted(kinds.items())) + ")" if kinds else "",
                                     ", oldest %d days" % max(ages) if ages else ""))
    print("Untested:       %d source files have no test file with a matching name" % len(data["untested"]))
    print("Long functions: %d over %d lines" % (len(data["functions"]), LONG_FUNCTION))
    print("Large files:    %d over %d lines" % (len(data["large_files"]), LARGE_FILE))
    print("Duplication:    %d blocks, %d lines" % (len(data["duplication"]), sum(d["lines"] for d in data["duplication"])))
    for t in data["tools"]:
        print("Tool %-10s %s" % (t["tool"] + ":", "%d findings" % len(t["findings"]) if t["ran"] else "not run, " + t["reason"]))
    if data["unmeasured_languages"]:
        print("Function length is not measured for: %s" % ", ".join(data["unmeasured_languages"]))
    print("\nStart here")
    for i, r in enumerate(data["ranked"], 1):
        print("%2d  %s  score %.2f  %s" % (i, r["file"], r["score"], ", ".join(describe(x) for x in r["reasons"])))
    if not data["ranked"]:
        print("    nothing to rank")
    print("\nData:   %s" % tilde(os.path.join(sdir, "scan.json")))
    print("Report: %s" % tilde(os.path.join(sdir, "report.html")))


def write_json(path, obj):
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(obj, fh, indent=1, ensure_ascii=False)
    os.chmod(tmp, 0o600)
    os.replace(tmp, path)


def build_report(sdir):
    with open(os.path.join(sdir, "scan.json"), encoding="utf-8") as fh:
        data = json.load(fh)
    notes_path = os.path.join(sdir, "notes.json")
    notes = {}
    if os.path.isfile(notes_path):
        with open(notes_path, encoding="utf-8") as fh:
            notes = json.load(fh)
    with open(TEMPLATE, encoding="utf-8") as fh:
        page = fh.read()
    payload = json.dumps({"data": data, "notes": notes}, ensure_ascii=False)
    payload = payload.replace("</", "<\\/")
    page = page.replace("/*TECHDEBT_DATA*/null", payload).replace("{{TITLE}}", html.escape(data["project"]))
    out = os.path.join(sdir, "report.html")
    tmp = out + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(page)
    os.chmod(tmp, 0o600)
    os.replace(tmp, out)
    return out


def load_notes(path, data):
    try:
        with open(path, encoding="utf-8") as fh:
            notes = json.load(fh)
    except (OSError, ValueError) as e:
        return None, "the notes file could not be read as JSON (%s)" % type(e).__name__
    if not isinstance(notes, dict):
        return None, "the notes file must be a JSON object keyed by file path"
    ranked = {r["file"] for r in data["ranked"]}
    errors = []
    for k, v in notes.items():
        if k not in ranked:
            errors.append("%s is not in the ranked list" % k)
        elif not isinstance(v, dict) or not all(isinstance(v.get(f), str) and v.get(f).strip() for f in ("what", "why", "action")):
            errors.append("%s needs non-empty what, why, and action" % k)
    if errors:
        return None, "; ".join(errors)
    return {k: {f: notes[k][f].strip() for f in ("what", "why", "action")} for k in notes}, None


def main(argv):
    ap = argparse.ArgumentParser(prog="techdebt.py", description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("scan", help="measure the repository and build the report")
    s.add_argument("root", nargs="?", default=".")
    s.add_argument("--months", type=int, default=12)
    e = sub.add_parser("explain", help="attach notes to ranked files and rebuild the report")
    e.add_argument("--notes", required=True)
    e.add_argument("root", nargs="?", default=".")
    r = sub.add_parser("report", help="rebuild the report from the last scan")
    r.add_argument("root", nargs="?", default=".")
    args = ap.parse_args(argv)
    root = os.path.realpath(args.root)
    if not os.path.isdir(root):
        print("not a folder: %s" % args.root, file=sys.stderr)
        return 3
    if args.cmd == "scan":
        if args.months < 1:
            print("--months must be 1 or more", file=sys.stderr)
            return 2
        sdir = state_dir(root)
        data = scan(root, args.months)
        write_json(os.path.join(sdir, "scan.json"), data)
        stale = os.path.join(sdir, "notes.json")
        if os.path.isfile(stale):
            with open(stale, encoding="utf-8") as fh:
                old = json.load(fh)
            keep = {k: v for k, v in old.items() if k in {x["file"] for x in data["ranked"]}}
            write_json(stale, keep)
        build_report(sdir)
        print_summary(data, sdir)
        return 0
    sdir = state_dir(root)
    if not os.path.isfile(os.path.join(sdir, "scan.json")):
        print("no scan for %s yet; run scan first" % root, file=sys.stderr)
        return 2
    if args.cmd == "explain":
        with open(os.path.join(sdir, "scan.json"), encoding="utf-8") as fh:
            data = json.load(fh)
        notes, err = load_notes(args.notes, data)
        if err:
            print("notes not saved: %s" % err, file=sys.stderr)
            return 2
        merged = {}
        old = os.path.join(sdir, "notes.json")
        if os.path.isfile(old):
            with open(old, encoding="utf-8") as fh:
                merged = json.load(fh)
        merged.update(notes)
        write_json(old, merged)
        print("saved notes for %d files" % len(notes))
    print("Report: %s" % tilde(build_report(sdir)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

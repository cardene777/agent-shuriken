def run_knip(root):
    exe = os.path.join(root, "node_modules", ".bin", "knip")
    if not os.path.isfile(os.path.join(root, "package.json")):
        return None
    if not os.access(exe, os.X_OK):
        return {"tool": "knip", "ran": False, "reason": "knip is not installed in node_modules/.bin", "findings": []}
    try:
        r = subprocess.run([exe, "--reporter", "json", "--no-progress"], cwd=root, capture_output=True, timeout=600)
        data = json.loads(r.stdout.decode("utf-8", "replace") or "{}")
    except subprocess.TimeoutExpired:
        return {"tool": "knip", "ran": False, "reason": "knip did not finish within 10 minutes", "findings": []}
    except (OSError, ValueError) as e:
        return {"tool": "knip", "ran": False, "reason": "knip output could not be read (%s)" % type(e).__name__, "findings": []}
    found = []
    for f in data.get("files", []) or []:
        found.append({"file": f, "line": 0, "rule": "unused-file", "message": "Unused file"})
    for issue in data.get("issues", []) or []:
        f = issue.get("file", "")
        for key, rule in (("dependencies", "unused-dependency"), ("devDependencies", "unused-devDependency"),
                          ("exports", "unused-export"), ("types", "unused-type"), ("unlisted", "unlisted-dependency")):
            for item in issue.get(key, []) or []:
                name = item.get("name", "") if isinstance(item, dict) else str(item)
                line = item.get("line", 0) if isinstance(item, dict) else 0
                found.append({"file": f, "line": line or 0, "rule": rule, "message": "%s: %s" % (rule.replace("-", " "), name)})
    return {"tool": "knip", "ran": True, "reason": "", "findings": found}


def run_ruff(root, has_python):
    if not has_python:
        return None
    exe = os.path.join(root, ".venv", "bin", "ruff")
    if not os.access(exe, os.X_OK):
        exe = shutil.which("ruff")
    if not exe:
        return {"tool": "ruff", "ran": False, "reason": "ruff is not installed in .venv/bin or on PATH", "findings": []}
    try:
        r = subprocess.run([exe, "check", "--select", "C901,PLR0911,PLR0912,PLR0913,PLR0915",
                            "--output-format", "json", "--exit-zero", "--no-cache", "."],
                           cwd=root, capture_output=True, timeout=600)
        data = json.loads(r.stdout.decode("utf-8", "replace") or "[]")
    except subprocess.TimeoutExpired:
        return {"tool": "ruff", "ran": False, "reason": "ruff did not finish within 10 minutes", "findings": []}
    except (OSError, ValueError) as e:
        return {"tool": "ruff", "ran": False, "reason": "ruff output could not be read (%s)" % type(e).__name__, "findings": []}
    found = []
    for d in data:
        f = d.get("filename", "")
        if os.path.isabs(f):
            f = os.path.relpath(os.path.realpath(f), root)
        found.append({"file": f, "line": (d.get("location") or {}).get("row", 0), "rule": d.get("code", ""),
                      "message": d.get("message", "")})
    return {"tool": "ruff", "ran": True, "reason": "", "findings": found}



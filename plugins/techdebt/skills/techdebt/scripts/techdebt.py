def scan(root, months):
    in_git = is_git(root)
    paths = repo_paths(root, in_git)
    files = list_files(root, in_git, paths)
    counts, commits = churn(root, months) if in_git else ({}, 0)
    now = time.time()
    per = {}
    texts = {}
    markers = []
    functions = []
    large = []
    tests = [p for p in files if is_test(p)]
    test_stems = {stem(p) for p in tests}
    skipped_generated = 0
    fn_note = set()
    for p in files:
        lines = read_lines(root, p)
        if lines is None:
            continue
        if any(GENERATED.search(l) for l in lines[:5]):
            skipped_generated += 1
            continue
        lang = LANG[os.path.splitext(p)[1].lower()]
        loc = sum(1 for l in lines if l.strip())
        test = p in tests
        per[p] = {"path": p, "lang": lang, "lines": loc, "changes": counts.get(p, 0), "test": test,
                  "markers": 0, "long_functions": 0, "dup_lines": 0, "untested": False}
        if not test:
            texts[p] = lines
        for n, kind, text in markers_in(lines, lang):
            markers.append({"file": p, "line": n, "kind": kind, "text": text, "age_days": None})
            per[p]["markers"] += 2 if kind in ("FIXME", "HACK") else 1
        if loc > LARGE_FILE and not test:
            large.append({"file": p, "lines": loc})
        if test:
            continue
        if lang == "python":
            fns = python_functions("\n".join(lines))
        elif lang in BRACE_LANGS:
            fns = brace_functions(lines, lang)
        else:
            fns = None
            fn_note.add(lang)
        for name, a, b, c in fns or []:
            length = b - a + 1
            if length > LONG_FUNCTION:
                functions.append({"file": p, "name": name, "start": a, "end": b, "lines": length,
                                  "complexity": c, "exact": lang == "python"})
                per[p]["long_functions"] += 1
        if lang not in ("shell", "lua", "haskell", "clojure") and loc >= 20:
            name = os.path.basename(p)
            if not NOT_SOURCE.search(name) and stem(p) not in test_stems:
                if not (lang == "rust" and any("#[cfg(test)]" in l for l in lines)):
                    per[p]["untested"] = True
    # Ages of markers.
    if in_git:
        by_file = {}
        for m in markers:
            by_file.setdefault(m["file"], []).append(m)
        for i, (p, ms) in enumerate(sorted(by_file.items())):
            if i >= MAX_BLAME_FILES:
                break
            times = blame_times(root, p)
            for m in ms:
                t = times.get(m["line"])
                m["age_days"] = None if t is None else int((now - t) // 86400)
    markers.sort(key=lambda m: -(m["age_days"] if m["age_days"] is not None else -1))
    dups = duplication(texts)
    for d in dups:
        per[d["a"]]["dup_lines"] += d["lines"]
        per[d["b"]]["dup_lines"] += d["lines"]
    functions.sort(key=lambda f: -f["lines"])
    large.sort(key=lambda f: -f["lines"])
    hotspots = sorted((v for v in per.values() if v["changes"] >= 2 and not v["test"]),
                      key=lambda v: -(v["changes"] * v["lines"]))
    untested = sorted((v for v in per.values() if v["untested"]), key=lambda v: -(v["changes"] * v["lines"] + v["lines"]))
    knip = run_knip(root)
    ruff, ruff_status, ruff_calls = run_ruff(root, any(v["lang"] == "python" for v in per.values()))
    semgrep, semgrep_status, semgrep_calls = run_semgrep(root)
    eslint_status, eslint_calls = run_eslint(root, list(per))
    tools = [t for t in (knip, ruff, semgrep) if t]
    deprecated = {"tools": [ruff_status, semgrep_status, eslint_status],
                  "items": sorted(ruff_calls + semgrep_calls + eslint_calls, key=lambda c: (c["file"], c["line"], c["tool"]))}
    unused_deps = knip_dependencies(knip) if knip and knip["ran"] else find_unused_dependencies(root, paths)
    ranked = rank(per)
    head = git(root, "rev-parse", "--short", "HEAD") if in_git else None
    branch = git(root, "rev-parse", "--abbrev-ref", "HEAD") if in_git else None
    return {
        "schema": SCHEMA,
        "root": root,
        "project": os.path.basename(root),
        "generated_at": dt.datetime.now(dt.timezone.utc).astimezone().isoformat(timespec="seconds"),
        "git": in_git,
        "head": head.stdout.decode().strip() if head is not None and head.returncode == 0 else "",
        "branch": branch.stdout.decode().strip() if branch is not None and branch.returncode == 0 else "",
        "months": months,
        "commits": commits,
        "files": len(per),
        "test_files": len(tests),
        "skipped_generated": skipped_generated,
        "approximate_languages": sorted(l for l in {v["lang"] for v in per.values()} if l in BRACE_LANGS),
        "unmeasured_languages": sorted(fn_note),
        "ranked": ranked,
        "hotspots": [{"file": v["path"], "changes": v["changes"], "lines": v["lines"]} for v in hotspots],
        "markers": markers,
        "untested": [{"file": v["path"], "changes": v["changes"], "lines": v["lines"]} for v in untested],
        "functions": functions,
        "large_files": large,
        "duplication": dups,
        "unused_dependencies": unused_deps,
        "deprecated_calls": deprecated,
        "tools": tools,
        "thresholds": {"long_function": LONG_FUNCTION, "large_file": LARGE_FILE, "duplicate_lines": DUP_WINDOW},
    }


def rank(per):
    """Score each source file from 0 to 1 by combining the measures, and keep the top files."""
    files = [v for v in per.values() if not v["test"]]

    def norm(key):
        top = max((key(v) for v in files), default=0) or 1
        return lambda v: key(v) / top

    hot = norm(lambda v: v["changes"] * v["lines"])
    mk = norm(lambda v: v["markers"])
    lf = norm(lambda v: v["long_functions"])
    dup = norm(lambda v: v["dup_lines"])
    ch = norm(lambda v: v["changes"])
    out = []
    for v in files:
        score = 0.4 * hot(v) + 0.15 * mk(v) + 0.2 * lf(v) + 0.15 * dup(v) + (0.1 * ch(v) if v["untested"] else 0)
        if score <= 0:
            continue
        reasons = []
        if v["changes"]:
            reasons.append({"key": "changes", "value": v["changes"]})
        reasons.append({"key": "lines", "value": v["lines"]})
        if v["long_functions"]:
            reasons.append({"key": "long_functions", "value": v["long_functions"]})
        if v["markers"]:
            reasons.append({"key": "markers", "value": v["markers"]})
        if v["dup_lines"]:
            reasons.append({"key": "dup_lines", "value": v["dup_lines"]})
        if v["untested"]:
            reasons.append({"key": "untested", "value": 1})
        out.append({"file": v["path"], "score": round(score, 3), "reasons": reasons})
    out.sort(key=lambda x: (-x["score"], x["file"]))
    return out[:TOP]



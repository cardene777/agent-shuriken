#!/usr/bin/env python3
"""Measure technical debt in a repository and rank the files most worth fixing.

Usage:

  techdebt.py scan [ROOT] [--months N]
  techdebt.py explain --notes FILE [ROOT]
  techdebt.py report [ROOT]

`scan` measures ROOT (default: the current folder) with the Python standard library and `git`:

  - hotspots: commits per file in the last N months (default 12) and non-blank lines
  - markers: TODO, FIXME, HACK, XXX, and deprecation markers in comments, aged with `git blame`
  - untested: source files with no test file of a matching name
  - long functions: over 60 lines (Python exactly with `ast`, brace languages approximately)
  - large files: over 500 non-blank lines
  - duplication: blocks of 8 or more lines that appear in two places

It also runs `knip` and `ruff` when they are already installed in the project or on PATH, and
never downloads anything. It ranks files by combining the measures, writes scan.json and an
HTML report to the state folder, and prints a summary.

`explain` attaches the agent's notes to ranked files and rebuilds the report. The notes file is
JSON: {"<path>": {"what": "...", "why": "...", "action": "..."}}.

The state folder is ~/.local/share/techdebt/<project>-<hash>/, or under TECHDEBT_HOME when set.

Exit codes: 0 done, 2 bad arguments or notes, 3 ROOT is not a folder.
"""

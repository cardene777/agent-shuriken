def churn(root, months):
    since = "%d.months.ago" % months
    # --relative keeps paths relative to ROOT, which may be a folder inside the repository.
    r = git(root, "log", "--since=" + since, "--no-renames", "--relative", "--format=@@%H", "--name-only")
    counts = {}
    commits = 0
    for line in r.stdout.decode("utf-8", "replace").splitlines():
        if line.startswith("@@"):
            commits += 1
        elif line.strip():
            counts[line.strip()] = counts.get(line.strip(), 0) + 1
    return counts, commits


def comment_part(line, lang):
    """The comment on this line, found outside string literals, or None."""
    stripped = line.lstrip()
    if stripped.startswith(("*", '"""', "'''")) and lang not in ("shell",):
        return stripped
    tokens = COMMENT_TOKENS.get(lang, C_TOKENS)
    q = None
    i = 0
    while i < len(line):
        ch = line[i]
        if q:
            if ch == "\\":
                i += 2
                continue
            if ch == q:
                q = None
        elif ch in "\"'`":
            q = ch
        else:
            for tok in tokens:
                if line.startswith(tok, i):
                    return line[i:]
        i += 1
    return None


def _hide_assignments(text):
    out, pos = [], 0
    for m in ASSIGNMENT.finditer(text):
        v = VALUE.match(text, m.end())
        if m.start() < pos or not v:
            continue
        name, sep = m.groups()
        quote, value = v.groups()
        secret_name = SECRET_NAME.search(name)
        if "=" in sep:
            hide = ENV_NAME.fullmatch(name) or secret_name
        else:
            hide = secret_name and (quote or re.search(r"[^A-Za-z_-]", value))
        if hide:
            out.append(text[pos:m.end()] + quote + "***")
            pos = v.end()
    return "".join(out) + text[pos:]


def _hide_long_token(m):
    s = m.group(0)
    if not (re.search("[a-z]", s) and re.search("[A-Z]", s) and re.search("[0-9]", s)):
        return s
    words = WORD.findall(s)
    return "***" if sum(map(len, words)) / len(words) < 4 else s


def mask(text):
    """The text with the home folder written as `~` and anything that looks like a secret as ***."""
    home = os.path.expanduser("~").rstrip(os.sep)
    if len(home) > 1:
        text = re.sub(re.escape(home) + r"(?![A-Za-z0-9_.-])", "~", text)
    text = KEY_SHAPES.sub("***", text)
    text = URL_LOGIN.sub(r"\1***@", text)
    text = AUTH_HEADER.sub(lambda m: m.group(1) + " ***", text)
    text = _hide_assignments(text)
    return LONG_TOKEN.sub(_hide_long_token, text)


def markers_in(lines, lang):
    found = []
    for n, line in enumerate(lines, 1):
        kind = None
        comment = comment_part(line, lang)
        if comment:
            mk = MARKER.search(comment)
            kind = mk.group(1) if mk else None
        if not kind and DEPRECATED.search(line):
            kind = "deprecated"
        if kind:
            # Mask the whole line first, so a secret cut at the 200th character is still caught
            found.append((n, kind, mask(line.strip())[:200]))
    return found


def blame_times(root, path):
    r = git(root, "blame", "--line-porcelain", "-w", "--", path)
    if r.returncode != 0:
        return {}
    times = {}
    cur = None
    uncommitted = False
    for line in r.stdout.decode("utf-8", "replace").splitlines():
        if re.match(r"^[0-9a-f]{40} \d+ \d+", line):
            parts = line.split()
            cur = int(parts[2])
            uncommitted = parts[0] == "0" * 40
        elif line.startswith("author-time ") and cur is not None:
            times[cur] = None if uncommitted else int(line.split()[1])
    return times


def python_functions(text):
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return None
    out = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            c = 1
            for sub in ast.walk(node):
                if isinstance(sub, (ast.If, ast.For, ast.AsyncFor, ast.While, ast.IfExp, ast.ExceptHandler,
                                    ast.With, ast.AsyncWith, ast.Assert)):
                    c += 1
                elif isinstance(sub, ast.BoolOp):
                    c += len(sub.values) - 1
                elif isinstance(sub, ast.comprehension):
                    c += 1 + len(sub.ifs)
                elif hasattr(ast, "match_case") and isinstance(sub, ast.match_case):
                    c += 1
            out.append((node.name, node.lineno, node.end_lineno, c))
    return out


def code_only(lines):
    """Each line with string literals and comments blanked, so braces inside them are not counted.

    Strings are tracked within a line; block comments are tracked across lines."""
    out = []
    in_block = False
    for line in lines:
        buf = []
        i = 0
        q = None
        while i < len(line):
            if in_block:
                end = line.find("*/", i)
                if end < 0:
                    i = len(line)
                    break
                in_block = False
                i = end + 2
                continue
            ch = line[i]
            if q:
                if ch == "\\":
                    i += 2
                    continue
                if ch == q:
                    q = None
                i += 1
                continue
            if ch in "\"'`":
                q = ch
                i += 1
                continue
            if line.startswith("//", i):
                break
            if line.startswith("/*", i):
                in_block = True
                i += 2
                continue
            buf.append(ch)
            i += 1
        out.append("".join(buf))
    return out


def header_name(line, lang):
    header = BRACE_HEADERS.get(lang)
    m = header.match(line) if header else None
    if m:
        name = next((g for g in m.groups() if g), None)
    elif lang in ("java", "c", "php", "swift"):
        g = GENERIC_HEADER.match(line)
        name = g.group(1) if g else None
    else:
        name = None
    return None if not name or name in CONTROL else name


def brace_functions(lines, lang):
    """(name, first line, last line, complexity) for each function, found by matching braces."""
    codes = code_only(lines)
    out = []
    n = len(lines)
    for i in range(n):
        name = header_name(codes[i], lang)
        if not name:
            continue
        depth = 0
        opened = False
        end = None
        j = i
        while j < n and end is None:
            for ch in codes[j]:
                if ch == "{":
                    depth += 1
                    opened = True
                elif ch == "}":
                    depth -= 1
                    if opened and depth <= 0:
                        end = j
                        break
            if not opened and (";" in codes[j] or j >= i + 3):
                break
            j += 1
        if end is not None and end > i:
            body = "\n".join(codes[i:end + 1])
            out.append((name, i + 1, end + 1, 1 + len(COMPLEXITY.findall(body))))
    return out


def normalize(line):
    s = " ".join(line.strip().split())
    if not s or len(s) < 3 or re.fullmatch(r"[\s{}()\[\];,.:]*|end|else|\}\s*else\s*\{", s):
        return None
    if IMPORT_LINE.match(s) or s.startswith(("//", "#", "*", "/*", "--")):
        return None
    return s


def duplication(texts):
    """Blocks of DUP_WINDOW or more normalized lines that appear in two places."""
    norm = {}
    index = {}
    for path, lines in texts.items():
        seq = [(n, s) for n, s in ((n, normalize(l)) for n, l in enumerate(lines, 1)) if s]
        norm[path] = seq
        for k in range(len(seq) - DUP_WINDOW + 1):
            window = [s for _, s in seq[k:k + DUP_WINDOW]]
            if sum(len(s) for s in window) < DUP_MIN_CHARS:
                continue
            h = hashlib.sha1("\n".join(window).encode()).digest()
            index.setdefault(h, []).append((path, k))
    pairs = {}
    for h, occ in index.items():
        if len(occ) < 2 or len(occ) > 20:
            continue
        for a in range(len(occ)):
            for b in range(a + 1, len(occ)):
                (pa, ka), (pb, kb) = occ[a], occ[b]
                if pa == pb and abs(ka - kb) < DUP_WINDOW:
                    continue
                if (pa, ka) > (pb, kb):
                    (pa, ka), (pb, kb) = (pb, kb), (pa, ka)
                pairs.setdefault((pa, pb), set()).add((ka, kb))
    blocks = []
    for (pa, pb), starts in pairs.items():
        for ka, kb in sorted(starts):
            if (ka - 1, kb - 1) in starts:
                continue
            run = 1
            while (ka + run, kb + run) in starts:
                run += 1
            last = run + DUP_WINDOW - 2
            sa, sb = norm[pa], norm[pb]
            a1, a2 = sa[ka][0], sa[ka + last][0]
            b1, b2 = sb[kb][0], sb[kb + last][0]
            blocks.append({"a": pa, "a_start": a1, "a_end": a2, "b": pb, "b_start": b1, "b_end": b2,
                           "lines": run + DUP_WINDOW - 1})
    blocks.sort(key=lambda x: -x["lines"])
    return blocks


